//Задание 4: "Расчет бонусных баллов"
//Клиенты интернет-магазина получают бонусные баллы за покупки. Напишите функцию,
// которая принимает сумму покупки и печатает в консоль количество бонусных баллов:
// 2 балла за каждые 100 рублей при сумме покупки до 1000 рублей и 3 балла за каждые 100 рублей
// при сумме свыше этого.
fun example4(purchaseSum: Double) {
    var result = 0.0
    if (purchaseSum in 1.0..999.99) {
        result = purchaseSum / 100 * 2
    } else if (purchaseSum >= 1000) {
        result = 1000 / 100 * 2 + (purchaseSum-1000) / 100 * 3
    }
    println(result.toInt())
}

