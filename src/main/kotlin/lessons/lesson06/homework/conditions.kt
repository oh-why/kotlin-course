//Задание 1: "Определение сезона"
//Напишите функцию, которая на основе номера месяца распечатывает сезон года.
// Номера месяцев начинаются с единицы.
fun example1(monNum: Int) {
    when {
        monNum in 1..2 || monNum == 12 -> println("winter")
        monNum in 3..5 -> println("spring")
        monNum in 6..8 -> println("summer")
        monNum in 9..11 -> println("autumn")
        else -> println("???")
    }
}

//Задание 2: "Расчет возраста питомца"
//Создайте функцию, которая преобразует возраст собаки в "человеческие" годы.
// До 2 лет каждый год собаки равен 10.5 человеческим годам, после - каждый год равен
// 4 человеческим годам. Результат распечатай в консоль.
fun example2(dogAge: Int) {
    var result = 0.0
    if (dogAge in 1..2) {
        result = dogAge * 10.5
    } else if (dogAge > 2) {
        result = 2*10.5 + dogAge*4.0
    }
    println(result)
}

