//Цель: Привести все слова в списке к нижнему регистру, сгруппировать в каталог по первой
// букве используя метод groupBy
fun mapCatalogue(arg: List<String>): Map<String, List<String>> {
    return arg.groupBy { it[0].lowercase() }.toSortedMap()
}

//Задание 27. Подсчёт средней длины слов в списке
//Напиши функцию, которая принимает список строк и возвращает строку.
//Начальные значения взять из предыдущей задачи.
//Цель: Перевести все слова в количество букв, подсчитать среднее значение. Вернуть форматированный
// текст с двумя знаками после запятой, используя функцию format и подходящий шаблон.
fun avgWordLength(arg: List<String>): String {
    val lengths = arg.map { it.length }
    return "%.2f".format(lengths.average())
}

//Задание 28: Категоризация чисел
//Напиши функцию, которая принимает список чисел и возвращает словарь с ключами - строками и
// значениями - список чисел.
//Начальные значения: val numbers = listOf(1, 3, 5, 7, 3, 1, 8, 9, 9, 7)
//Цель: Отобрать уникальные числа, отсортировать по убыванию и сгруппировать по четности
// (“четные” и “нечетные”).
fun numCategories(arg: List<Int>): Map<String, List<Int>> {
    return arg.distinct()
        .sortedDescending()
        .groupBy { if (it % 2 == 0) "четные" else "нечетные" }
}

//Задание 29: Поиск первого подходящего элемента
//Напиши функцию, которая принимает список чисел и число и возвращает nullable число.
//Начальные значения: val ages = listOf(22, 18, 30, 45, 17, null, 60) и число для проверки возраста,
// например 18.
//Цель: Найти первый возраст в списке, который соответствует условию (больше второго аргумента) и
// вернуть его, либо null если значения не нашлось.
fun firstMatch(arg1: List<Int?>, arg2: Int): Int? {
    return arg1.firstOrNull { it!! > arg2 }
}
