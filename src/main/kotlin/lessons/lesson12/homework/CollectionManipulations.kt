//Задача 24. Характеристика числовой коллекции
//Напиши функцию, которая принимает коллекцию чисел и возвращает строку с характеристикой
// коллекции используя конструкцию when
//Если коллекция пустая - “Пусто”
//Если количество элементов меньше пяти - “Короткая”
//Если коллекция начинается с 0 - “Стартовая”
//Если сумма всех чисел больше 10000 - “Массивная”
//Если среднее значение равно 10 - “Сбалансированная”
//Если длина строки образованная склеиванием коллекции в строку равна 20 - “Клейкая”
//Если максимальное число меньше -10 - “Отрицательная”
//Если минимальное число больше 1000 - “Положительная”
//Если содержит одновременно числа 3 и 14 - “Пи***тая”
//Иначе - “Уникальная”
//Вызвать метод с данными, подходящими под каждую из веток
fun collectionFeature(arg: List<Int>): String {
    var value = "Уникальная"
    when {
        arg.isEmpty() -> value = "Пусто"
        arg.size < 5 -> value = "Короткая"
        arg.elementAt(0) == 0 -> value = "Стартовая"
        arg.sum() > 10000 -> value = "Массивная"
        arg.average() == 10.0 -> value = "Сбалансированная"
        arg.joinToString("").length == 20 -> value = "Клейкая"
        arg.max() < -10 -> value = "Отрицательная"
        arg.min() > 1000 -> value = "Положительная"
        arg.contains(3) && arg.contains(14) -> value = "Пи***тая"
    }
    println(value)
    return value
}

//Задача 25. Анализ учебных оценок
//Напиши функцию, которая принимает список чисел и возвращает список чисел.
//Пример данных: val grades = listOf(85, 58, 90, 74, 88, 67, 95, 92, 50, 42, 12)
//Цель: Отфильтровать удовлетворительные оценки (>=60), отсортировать оставшиеся по возрастанию
// и взять первые 3. Вызывай методы обработки и фильтрации последовательно один из другого,
// чтобы результат предыдущего метода являлся основой для следующего.
fun filterGrades(arg: List<Int>): List<Int> {
    return arg.filter { it >= 60 }
        .sorted()
        .take(3)
}

