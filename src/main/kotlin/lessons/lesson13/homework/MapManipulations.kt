    val e23 = mapOf("1.0" to 100.0, "1.1" to 120.0, "2.0" to 90.0)
    val e23v1 = e23.mapValues { (_, v) -> v * 1.1 }
    println(e23v1)
    //Проверьте, пуст ли словарь с ошибками компиляции тестов.
    val e24 = mapOf<String, String>()
    println(e24.isEmpty())
    //Убедитесь, что словарь с результатами нагрузочного тестирования не пуст.
    val e25 = mapOf("rps" to 1000, "errors" to 0)
    println(e25.isNotEmpty())
    //Проверьте, прошли ли успешно все автоматизированные тесты в словаре с результатами.
    val e26 = mapOf("t1" to "passed", "t2" to "passed")
    println(e26.all { it.value == "passed" })
    //Определите, содержит ли словарь с результатами тестирования хотя бы один тест с ошибкой.
    println(e26.any { it.value == "failed" })
//Отфильтруйте словарь с результатами тестирования сервисов, оставив только те тесты, которые не прошли
// успешно и содержат в названии “optional”.
    val e28 = e26.filter { (name, status) ->
        status != "passed" && name.contains("optional")
    }
    println(e28)
}
